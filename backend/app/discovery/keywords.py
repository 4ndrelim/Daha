# Multi-word keys first so "bike pump" wins over "bike", "help with" over "help".
_ORDERED = sorted(
    ((kw, cat) for cat, kws in CATEGORY_KEYWORDS.items() for kw in kws),
    key=lambda kc: -len(kc[0]),
)
_PATTERNS = [(re.compile(rf"\b{re.escape(kw)}(e?s)?\b", re.I), cat) for kw, cat in _ORDERED]
_SERVICE_INTENT = re.compile(
    r"\b(someone who can|somebody who can|anyone who can|help (me )?(with|repair|fix|move)|"
    r"repair|fix(ing)?|tutor(ing)?|lessons?|teach)\b",
    re.I,
)


def category_for(text: str) -> str | None:
    if _SERVICE_INTENT.search(text):
        return "services"
    for pattern, cat in _PATTERNS:
        if pattern.search(text):
            return cat
    return None
